// Generates db/supabase/002_seed_mvp_scenario.sql from src/domain/fixtures.ts.
// The fixture object is plain JSON, so the MVP scenario has one source of truth:
// change fixtures.ts, re-run `node scripts/gen_seed_sql.mjs`, re-apply the SQL.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(root, "src/domain/fixtures.ts"), "utf8");
const start = src.indexOf("{", src.indexOf("fixtures: DbState ="));
const body = src.slice(start, src.lastIndexOf("}") + 1);
const fx = JSON.parse(body);

const q = (v) => (v === undefined || v === null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const num = (v) => (v === undefined || v === null ? "null" : String(v));
const bool = (v) => (v ? "true" : "false");
const arr = (v) =>
  v === undefined || v === null ? "null" : `array[${v.map((x) => q(x)).join(", ")}]::text[]`;
const jsonb = (v) => `${q(JSON.stringify(v))}::jsonb`;
const ts = (v) => (v ? `${q(v)}::timestamptz` : "null");

const lines = [];
const w = (s = "") => lines.push(s);

w("-- MAE MVP demo scenario — generated by scripts/gen_seed_sql.mjs. Do not edit by hand.");
w("-- One project, one scan (scn-2001) and the eight MAE Golden Set v0.1 findings.");
w("-- Every record is synthetic and not human-validated.");
w("-- Safe to re-run: app_reset_demo() clears the app tables and re-seeds them.");
w("");
w("create or replace function public.app_seed_demo()");
w("returns void language plpgsql set search_path = public as $seed$");
w("begin");

w("  -- policy sources (the citation lookup table)");
for (const p of fx.policySources) {
  w(
    `  insert into public.app_policy_sources (id, title, status) values (${q(p.id)}, ${q(p.title)}, ${q(p.status)})`,
  );
  w("    on conflict (id) do update set title = excluded.title, status = excluded.status;");
}
w("");
w("  -- project");
for (const p of fx.projects) {
  w(
    `  insert into public.app_projects (id, name, base_url, owner, journeys, platforms) values (${q(p.id)}, ${q(p.name)}, ${q(p.baseUrl)}, ${q(p.owner)}, ${jsonb(p.journeys)}, ${arr(p.platforms)})`,
  );
  w("    on conflict (id) do nothing;");
}
w("");
w("  -- scan and its job");
for (const s of fx.scans) {
  w(
    `  insert into public.app_scans (id, project_id, target_url, scope, status, engines, created_by, created_at, completed_at) values (${q(s.id)}, ${q(s.projectId)}, ${q(s.targetUrl)}, ${q(s.scope)}, ${q(s.status)}, ${arr(s.engines)}, ${q(s.createdBy)}, ${ts(s.createdAt)}, ${ts(s.completedAt)})`,
  );
  w("    on conflict (id) do nothing;");
}
for (const j of fx.scanJobs) {
  w(
    `  insert into public.app_scan_jobs (id, scan_id, status, attempts, progress, updated_at) values (${q(j.id)}, ${q(j.scanId)}, ${q(j.status)}, ${num(j.attempts)}, ${num(j.progress)}, ${ts(j.updatedAt)})`,
  );
  w("    on conflict (id) do nothing;");
}
w("");
w("  -- the eight findings");
for (const f of fx.findings) {
  w(`  insert into public.app_findings (
    id, scan_id, golden_set_id, rule_id, title, description, callout, extra_note,
    journey, step_no, step_name, platform, screen_id, finding_type, wcag, wcag_criteria,
    wcag_version, conformance_level, baseline_status, severity, confidence, abstention_reason,
    evidence, node_ids, simulation_trace, affected_user_need, user_impact, affected_groups,
    recommended_fix, fix_rationale, verification_steps, gate_recommendation,
    requires_human_review, escalate_to, priority_score, priority_band, status,
    assignee, selector, page_url, created_at
  ) values (
    ${q(f.id)}, ${q(f.scanId)}, ${q(f.goldenSetId)}, ${q(f.ruleId)}, ${q(f.title)}, ${q(f.description)}, ${q(f.callout)}, ${q(f.extraNote)},
    ${q(f.journey)}, ${num(f.stepNo)}, ${q(f.stepName)}, ${q(f.platform)}, ${q(f.screenId)}, ${q(f.findingType)}, ${q(f.wcag)}, ${arr(f.wcagCriteria)},
    ${q(f.wcagVersion)}, ${q(f.conformanceLevel)}, ${q(f.baselineStatus)}, ${q(f.severity)}, ${q(f.confidence)}, ${q(f.abstentionReason)},
    ${q(f.evidence)}, ${arr(f.nodeIds)}, ${q(f.simulationTrace)}, ${q(f.affectedUserNeed)}, ${q(f.userImpact)}, ${arr(f.affectedGroups)},
    ${q(f.recommendedFix)}, ${q(f.fixRationale)}, ${q(f.verificationSteps)}, ${q(f.gateRecommendation)},
    ${bool(f.requiresHumanReview)}, ${q(f.escalateTo)}, ${num(f.priorityScore)}, ${q(f.priorityBand)}, ${q(f.status)},
    ${q(f.assignee)}, ${q(f.selector)}, ${q(f.pageUrl)}, ${ts(f.createdAt)}
  ) on conflict (id) do nothing;`);
  (f.policySources ?? []).forEach((p, i) => {
    w(
      `  insert into public.app_finding_policy_sources (finding_id, policy_source_id, position) values (${q(f.id)}, ${q(p.id)}, ${i}) on conflict do nothing;`,
    );
  });
  w("");
}
w("  -- evidence rows");
for (const e of fx.evidence) {
  w(
    `  insert into public.app_evidence (id, finding_id, kind, content) values (${q(e.id)}, ${q(e.findingId)}, ${q(e.kind)}, ${q(e.content)}) on conflict (id) do nothing;`,
  );
}
w("");
w("  -- open review tasks");
for (const t of fx.reviewTasks) {
  w(
    `  insert into public.app_review_tasks (id, finding_id, status, reviewer, decision_note, created_at, decided_at) values (${q(t.id)}, ${q(t.findingId)}, ${q(t.status)}, ${q(t.reviewer)}, ${q(t.decisionNote)}, ${ts(t.createdAt)}, ${ts(t.decidedAt)}) on conflict (id) do nothing;`,
  );
}
w("");
w("  -- seeded activity (no verified records: human-verified fixes must start at 0)");
for (const a of fx.auditEvents) {
  w(
    `  insert into public.app_audit_events (id, actor, action, entity, entity_id, created_at) values (${q(a.id)}, ${q(a.actor)}, ${q(a.action)}, ${q(a.entity)}, ${q(a.entityId)}, ${ts(a.createdAt)}) on conflict (id) do nothing;`,
  );
}
w("end $seed$;");
w("");
w("create or replace function public.app_reset_demo()");
w("returns void language plpgsql set search_path = public as $reset$");
w("begin");
w("  delete from public.app_audit_events where true;");
w("  delete from public.app_verification_runs where true;");
w("  delete from public.app_review_tasks where true;");
w("  delete from public.app_recommendations where true;");
w("  delete from public.app_model_runs where true;");
w("  delete from public.app_evidence where true;");
w("  delete from public.app_finding_policy_sources where true;");
w("  delete from public.app_findings where true;");
w("  delete from public.app_scan_jobs where true;");
w("  delete from public.app_scans where true;");
w("  delete from public.app_projects where true;");
w("  perform public.app_seed_demo();");
w("end $reset$;");
w("");
w(
  "revoke all on function public.app_seed_demo(), public.app_reset_demo() from public, anon, authenticated;",
);
w("grant execute on function public.app_seed_demo(), public.app_reset_demo() to service_role;");
w("");
w("-- seed now (idempotent)");
w("select public.app_seed_demo();");
w("");

const out = join(root, "db/supabase/002_seed_mvp_scenario.sql");
writeFileSync(out, lines.join("\n"), "utf8");
console.log(
  `wrote ${out}: ${fx.findings.length} findings, ${fx.policySources.length} policy sources, ${fx.evidence.length} evidence rows, ${fx.reviewTasks.length} review tasks, ${fx.auditEvents.length} audit events`,
);
